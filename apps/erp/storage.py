"""Database adapter for PostgreSQL and local SQLite fixtures."""

import sqlite3

try:
    import psycopg
except ImportError:
    psycopg = None

INTEGRITY_ERRORS = (sqlite3.IntegrityError,)
DATABASE_ERRORS = (sqlite3.OperationalError,)
if psycopg:
    INTEGRITY_ERRORS += (psycopg.IntegrityError,)
    DATABASE_ERRORS += (psycopg.Error,)


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def postgres_row(cursor):
    columns = [column.name for column in cursor.description or ()]
    return lambda values: Row(zip(columns, values))


class Postgres:
    def __init__(self, url):
        if psycopg is None:
            raise RuntimeError('PostgreSQL에는 psycopg가 필요합니다. requirements.txt를 설치하세요.')
        self.connection = psycopg.connect(url, row_factory=postgres_row, connect_timeout=5)

    def execute(self, sql, parameters=()):
        return self.connection.execute(sql.replace('?', '%s'), parameters or None)

    def executescript(self, sql):
        for statement in sql.split(';'):
            if statement.strip():
                self.execute(statement)

    def close(self):
        self.connection.close()

    def __enter__(self):
        return self

    def __exit__(self, error_type, *_):
        if error_type:
            self.connection.rollback()
        else:
            self.connection.commit()


def begin_write(db):
    if isinstance(db, Postgres):
        # Preserve atomic read/check/write behavior across all app workers.
        db.execute('SELECT pg_advisory_xact_lock(781935443)')
    else:
        db.execute('BEGIN IMMEDIATE')


def begin_read(db):
    if isinstance(db, Postgres):
        db.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY')
    else:
        db.execute('BEGIN')


def init_schema(db, schema):
    if isinstance(db, Postgres):
        begin_write(db)
        schema = schema.replace('id INTEGER PRIMARY KEY', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        schema = schema.replace(' REAL', ' DOUBLE PRECISION')
    db.executescript(schema)
